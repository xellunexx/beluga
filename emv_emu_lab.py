@dataclass
class TraceEntry:
    step: int
    phase: str
    direction: str
    name: str
    seq: Optional[int]
    apdu_hex: str
    status: str
    tlv_tags: List[str]
    detail: str
    reference: str


def hx(data: bytes) -> str:
    return bytes(data).hex().upper()


def sw(data: bytes) -> str:
    return hx(data[-2:]) if len(data) >= 2 else ""


def build_frame(sid: int, payload: bytes, *, epoch: int, seq: int) -> bytes:
    return constants.build_frame(
        sid,
        bytes(payload),
        seq=seq & 0xFFFF,
        epoch=epoch,
    )


def _tag_name(tag: Any) -> str:
    if isinstance(tag, int):
        return f"0x{tag:X}"
    return str(tag)


def response_tlv_tags(data: bytes) -> Tuple[List[str], List[str]]:
    """Return top-level TLV tags and parser notes without changing payload."""
    if len(data) < 3:
        return [], []

    body = data[:-2] if len(data) >= 2 else data
    if not body:
        return [], []

    try:
        nodes, errors = emv_parser.parse_ber_tlv(body)
        tags = [_tag_name(node.tag) for node in nodes]
        notes = [str(err) for err in errors]
        return tags, notes
    except Exception as exc:
        return [], [f"TLV parse error: {type(exc).__name__}: {exc}"]


def find_tag(data: bytes, tag: int) -> Optional[bytes]:
    """Best-effort lab diagnostic using the project's TLV helpers."""
    body = data[:-2] if len(data) >= 2 else data
    if not body:
        return None
    try:
        return tlv.find_tlv(body, tag)
    except Exception:
        return None


def decode_rapdu_checkpoint(data: bytes) -> Dict[str, Any]:
    tags, errors = response_tlv_tags(data)
    out: Dict[str, Any] = {
        "sw": sw(data),
        "tlv_tags": tags,
    }
    if errors:
        out["tlv_errors"] = errors

    for tag, label in (
        (0x9F27, "CID_9F27"),
        (0x9F36, "ATC_9F36"),
        (0x9F26, "AC_9F26"),
        (0x9F10, "IAD_9F10"),
        (0x91, "ISSUER_AUTH_91"),
    ):
        value = find_tag(data, tag)
        if value is not None:
            out[label] = hx(value)

    return out


class EmuLab:
    def __init__(
        self,
        relay_host: str,
        relay_port: int,
        *,
        session_id: Optional[str] = None,
        client_id: Optional[str] = None,
        timeout: float = 5.0,
        continue_arqc: bool = False,
        export_path: Optional[Path] = None,
        cdcvm: bool = False,
    ) -> None:
        self.relay_addr = (relay_host, int(relay_port))
        self.timeout = float(timeout)
        self.continue_arqc = bool(continue_arqc)
        self.export_path = Path(export_path) if export_path else None
        self.cdcvm = bool(cdcvm)

        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.sock.bind(("0.0.0.0", 0))
        self.sock.settimeout(0.20)

        self.epoch = 0
        self.protocol_state = "INIT"
        self.ctrl_messages: List[str] = []
        self.session_id = (
            session_id if session_id is not None else str(int(time.time()) % 10000)
        )
        self.client_id = client_id or f"REL8-LAB-EMU-{self.session_id}"
        self.trace: List[TraceEntry] = []
        self._step = 0
        self._seq = 0

    @property
    def local_addr(self) -> Tuple[str, int]:
        return self.sock.getsockname()

    def close(self) -> None:
        try:
            self.sock.close()
        except OSError:
            pass

    def _add_trace(
        self,
        *,
        phase: str,
        direction: str,
        name: str,
        seq: Optional[int],
        apdu: bytes,
        detail: str,
        reference: str = "",
    ) -> None:
        self._step += 1
        self.trace.append(
            TraceEntry(
                step=self._step,
                phase=phase,
                direction=direction,
                name=name,
                seq=seq,
                apdu_hex=hx(apdu),
                status=sw(apdu),
                tlv_tags=response_tlv_tags(apdu)[0] if direction == "RAPDU" else [],
                detail=detail,
                reference=reference,
            )
        )

    # ------------------------------------------------------------------
    # Registration/session control plane
    # ------------------------------------------------------------------

    def send_register(self) -> None:
        self.protocol_state = "REGISTERING"
        payload = (
            f"EMULATOR V{constants.PROTOCOL_VERSION} ID={self.client_id}"
        ).encode("utf-8")
        frame = build_frame(
            constants.SID_REGISTER,
            payload,
            epoch=0,
            seq=0,
        )
        self.sock.sendto(frame, self.relay_addr)
        print(
            f"REGISTER → {self.relay_addr[0]}:{self.relay_addr[1]} "
            f"id={self.client_id}"
        )

    def wait_for_register_ack(self) -> bool:
        deadline = time.monotonic() + self.timeout
        while time.monotonic() < deadline:
            try:
                data, _addr = self.sock.recvfrom(65535)
            except socket.timeout:
                continue

            parsed = constants.parse_frame(data)
            if parsed is None:
                continue

            sid, epoch, _seq, payload = parsed
            if sid == constants.SID_ACK:
                text = payload.decode("utf-8", errors="replace").strip()
                if text.upper() == "REGISTER":
                    self.epoch = epoch
                    self.protocol_state = "REGISTERED"
                    print(f"REGISTER ACK ← epoch={epoch}")
                    return True
            elif sid == constants.SID_CTRL:
                text = payload.decode("utf-8", errors="replace").strip()
                self.ctrl_messages.append(text)
                print(f"CTRL ← {text}")
                if text.upper().startswith("ERR "):
                    self.protocol_state = "ERROR"
                    return False
        return False

    def send_ctrl(self, text: str) -> None:
        command = text.strip().upper()
        if command.startswith("SESSION_BEGIN"):
            self.protocol_state = "SESSION_STARTING"
        frame = build_frame(
            constants.SID_CTRL,
            text.encode("utf-8"),
            epoch=self.epoch,
            seq=0,
        )
        self.sock.sendto(frame, self.relay_addr)
        print(f"CTRL → {text}")

    def wait_for_session_ack(self) -> bool:
        deadline = time.monotonic() + self.timeout
        while time.monotonic() < deadline:
            try:
                data, _addr = self.sock.recvfrom(65535)
            except socket.timeout:
                continue

            parsed = constants.parse_frame(data)
            if parsed is None:
                continue

            sid, epoch, _seq, payload = parsed
            self.epoch = epoch

            if sid == constants.SID_CTRL:
                text = payload.decode("utf-8", errors="replace").strip()
                self.ctrl_messages.append(text)
                print(f"CTRL ← {text}")
                command = text.upper()
                if command.startswith("ERR "):
                    self.protocol_state = "ERROR"
                    return False
                if command.startswith("SESSION_ACK") or command.startswith(
                    "SESSION_READY"
                ):
                    self.protocol_state = "SESSION_READY"
                    return True

            elif sid == constants.SID_ACK:
                text = payload.decode("utf-8", errors="replace").strip()
                print(f"ACK ← {text}")
                if text.upper() in {"SESSION_BEGIN", "SESSION", "READY"}:
                    self.protocol_state = "SESSION_READY"
                    return True

        self.protocol_state = "ERROR"
        return False

    # ------------------------------------------------------------------
    # APDU transport
    # ------------------------------------------------------------------

    def send_apdu(self, apdu: bytes, *, seq: int, phase: str, name: str) -> None:
        if self.protocol_state != "SESSION_READY":
            raise RuntimeError(
                f"cannot send APDU seq={seq}: state={self.protocol_state}"
            )

        self.protocol_state = "EXCHANGING"
        frame = build_frame(
            constants.SID_CAPDU,
            apdu,
            epoch=self.epoch,
            seq=seq,
        )
        self.sock.sendto(frame, self.relay_addr)

        self._add_trace(
            phase=phase,
            direction="CAPDU",
            name=name,
            seq=seq,
            apdu=apdu,
            detail=f"len={len(apdu)} epoch={self.epoch}",
        )

        print(
            f"CAPDU #{seq} → {name:24s} "
            f"len={len(apdu):2d} {hx(apdu)}"
        )

    def wait_for_rapdu(
        self,
        *,
        wanted_seq: int,
        phase: str,
        name: str,
        reference_response: Optional[bytes] = None,
    ) -> Optional[bytes]:
        deadline = time.monotonic() + self.timeout

        while time.monotonic() < deadline:
            try:
                data, _addr = self.sock.recvfrom(65535)
            except socket.timeout:
                continue

            parsed = constants.parse_frame(data)
            if parsed is None:
                continue

            sid, epoch, seq, payload = parsed
            self.epoch = epoch

            if sid == constants.SID_CTRL:
                text = payload.decode("utf-8", errors="replace").strip()
                self.ctrl_messages.append(text)
                print(f"CTRL ← {text}")
                if text.upper().startswith("ERR "):
                    self.protocol_state = "ERROR"
                    return None
                continue

            if sid != constants.SID_RAPDU:
                continue

            if seq != (wanted_seq & 0xFFFF):
                print(
                    f"IGNORING RAPDU seq={seq}; waiting for seq={wanted_seq}"
                )
                continue

            checkpoint = decode_rapdu_checkpoint(payload)
            reference = ""
            if reference_response is not None:
                if payload == reference_response:
                    reference = "EXACT_MATCH_KNOWN_GOOD"
                else:
                    reference = "DIFFERS_FROM_KNOWN_GOOD"

            self._step += 1
            self.trace.append(
                TraceEntry(
                    step=self._step,
                    phase=phase,
                    direction="RAPDU",
                    name=name,
                    seq=wanted_seq,
                    apdu_hex=hx(payload),
                    status=sw(payload),
                    tlv_tags=checkpoint.get("tlv_tags", []),
                    detail=json.dumps(checkpoint, sort_keys=True),
                    reference=reference,
                )
            )

            print(
                f"RAPDU #{wanted_seq} ← "
                f"len={len(payload):2d} SW={sw(payload)} "
                f"{hx(payload)}"
            )
            self._print_checkpoint(wanted_seq, checkpoint, reference)
            self.protocol_state = "SESSION_READY"
            return payload

        return None

    # ------------------------------------------------------------------
    # Diagnostic reporting
    # ------------------------------------------------------------------

    @staticmethod
    def _print_checkpoint(
        seq: int,
        checkpoint: Dict[str, Any],
        reference: str,
    ) -> None:
        print(f"  [CHECKPOINT #{seq}] SW={checkpoint.get('sw', '')}")
        if checkpoint.get("tlv_tags"):
            print(
                "  [TLV] "
                + ", ".join(checkpoint["tlv_tags"])
            )
        for label in ("CID_9F27", "ATC_9F36", "AC_9F26", "IAD_9F10", "ISSUER_AUTH_91"):
            if label in checkpoint:
                print(f"  [TLV] {label}={checkpoint[label]}")
        if reference:
            print(f"  [REFERENCE] {reference}")

    def print_trace(self) -> None:
        print()
        print("SIDE-BY-SIDE LAB CHECKPOINT TRACE")
        print("=" * 110)
        print(
            f"{'#':>2} {'PHASE':18s} {'DIR':7s} {'NAME':24s} "
            f"{'SEQ':>3} {'SW':>4} {'REFERENCE':28s}"
        )
        print("-" * 110)
        for item in self.trace:
            print(
                f"{item.step:2d} {item.phase:18.18s} {item.direction:7.7s} "
                f"{item.name:24.24s} "
                f"{str(item.seq) if item.seq is not None else '-':>3} "
                f"{item.status or '-':>4} "
                f"{item.reference or '-':28.28s}"
            )

        print("=" * 110)
        print("Use this trace as the lab-side baseline when comparing the real POS.")
        print("A real-POS stall at AID SELECT means the divergence occurs before")
        print("GPO; a stall after first GAC points at ARQC/issuer-auth handling.")

