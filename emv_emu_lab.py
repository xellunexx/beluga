"""
REL8HF EMV Emulator Lab -- protocol-aware captured transaction replay.

Laboratory scope
----------------
This program is a deterministic local test peer for the REL8HF relay. It does
not connect to an issuer/acquirer and it does not generate production payment
cryptographic values. The ARQC/AC fixtures used after the first GENERATE AC are
synthetic/captured lab values only.

The emulator:
  1. Registers as relay role EMULATOR.
  2. Waits for REGISTER ACK.
  3. Starts SESSION_BEGIN and waits for SESSION_ACK/READY.
  4. Replays the exact eight CAPDUs from the known-good transaction.
  5. Records detailed CAPDU/RAPDU checkpoints for comparison with a real POS.
  6. With --continue-arqc, continues the lab-only post-ARQC path using the
     same synthetic EXT AUTHENTICATE and second-GAC fixtures used by emv_lab1.

Wire format
-----------
Every UDP packet is built through constants.build_frame():
    Length(4) + SID(1) + Epoch(4) + Seq(2) + Payload(N)

APDU payloads are raw. The outer Seq is the CAPDU/RAPDU correlation value.
The optional EXCHANGE_MAGIC wrapper is intentionally not used.
"""

